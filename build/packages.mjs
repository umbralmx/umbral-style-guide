/**
 * Syncs the generated token data into the two packages.
 *
 *   tokens/build/* + rules/rules.json
 *        ↓  this script
 *   packages/umbral-viz/umbral_viz/_data/*     (byte-identical copies)
 *   packages/umbral-plot/src/tokens.js         (generated ES module)
 *   packages/umbral-plot/dist/umbral.css       (byte-identical copy)
 *
 * The packages would otherwise be the fourth and fifth place token values live,
 * after tokens/build/, the skill's assets/, and downstream raw-URL fetches. So they
 * do not embed values — the data is vendored here at build time and
 * `tools/verify_packages.py` asserts it is byte-identical to what the build
 * produced. A stale package fails CI rather than shipping wrong colours, which is
 * exactly how the v1.0 skill went a year handing out failing contrast.
 *
 * Run with `npm run build:packages` (part of `npm run build`).
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';

const VIZ_DATA = 'packages/umbral-viz/umbral_viz/_data';
const PLOT_SRC = 'packages/umbral-plot/src';
const PLOT_DIST = 'packages/umbral-plot/dist';

const tokens = JSON.parse(await fs.readFile('tokens/build/tokens.json', 'utf8'));
const rules = JSON.parse(await fs.readFile('rules/rules.json', 'utf8'));
const VERSION = rules.version;

await fs.mkdir(VIZ_DATA, { recursive: true });
await fs.mkdir(PLOT_SRC, { recursive: true });
await fs.mkdir(PLOT_DIST, { recursive: true });

// ── umbral-viz: vendored data, copied verbatim ────────────────────────────
const VIZ_COPIES = [
  'tokens.json',
  'contrast.json',
  'umbral-laboratorio.mplstyle',
  'umbral-instrumento.mplstyle',
  'plotly-umbral-laboratorio.json',
  'plotly-umbral-instrumento.json',
  'streamlit-config.toml',
];
for (const f of VIZ_COPIES) {
  await fs.copyFile(path.join('tokens/build', f), path.join(VIZ_DATA, f));
}
await fs.copyFile('rules/rules.json', path.join(VIZ_DATA, 'rules.json'));

await fs.writeFile(path.join(VIZ_DATA, 'README.md'), `# \`umbral_viz/_data/\`

**Generated by \`build/packages.mjs\`. Do not edit.**

Byte-identical copies of \`tokens/build/\` and \`rules/rules.json\` at v${VERSION}, vendored so the
package works offline and cannot disagree with the repo it came from.

\`tools/verify_packages.py\` compares every file here against the build and fails CI on any
difference. Nothing in \`umbral_viz/\` may write a colour, font or size as a literal — read it from
here.
`);

// ── umbral-plot: a generated ES module ────────────────────────────────────
const js = (o) => JSON.stringify(o, null, 2).replace(/\n/g, '\n');

await fs.writeFile(path.join(PLOT_SRC, 'tokens.js'), `/**
 * tokens.js — GENERATED from tokens/build/tokens.json at v${VERSION}. Do not edit.
 *
 * umbralmx/umbral-style-guide · code MIT · content CC BY 4.0
 */

export const version = ${js(VERSION)};

export const font = ${js(tokens.font)};

export const scale = ${js(tokens.scale)};

export const uncertaintyBandOpacity = ${js(tokens.uncertaintyBandOpacity)};

/** Semantic tokens, per mode. Read these; never retype a hex. */
export const mode = ${js(tokens.mode)};

/** Sequential and diverging ramps, per mode. */
export const ramp = ${js(tokens.ramp)};

export const modes = ['laboratorio', 'instrumento'];

/** Tokens for one mode. Throws rather than silently returning undefined. */
export function tokensFor(m = 'laboratorio') {
  if (!modes.includes(m)) {
    throw new Error(\`unknown Umbral mode "\${m}" — expected one of \${modes.join(', ')}\`);
  }
  return mode[m];
}

export default { version, font, scale, mode, ramp, modes, tokensFor, uncertaintyBandOpacity };
`);

await fs.copyFile('tokens/build/tokens.css', path.join(PLOT_DIST, 'umbral.css'));

await fs.writeFile(path.join(PLOT_DIST, 'README.md'), `# \`umbral-plot/dist/\`

**Generated by \`build/packages.mjs\`. Do not edit.**

| | |
|---|---|
| \`umbral.css\` | Byte-identical copy of \`tokens/build/tokens.css\` at v${VERSION} |

Import it alongside the theme so \`var(--u-*)\` resolves:

\`\`\`js
import '@umbralmx/umbral-plot/dist/umbral.css';
\`\`\`
`);

// keep both package manifests pinned to the design-system version
for (const [file, key] of [['packages/umbral-plot/package.json', 'version']]) {
  try {
    const pkg = JSON.parse(await fs.readFile(file, 'utf8'));
    if (pkg[key] !== VERSION) {
      pkg[key] = VERSION;
      await fs.writeFile(file, `${JSON.stringify(pkg, null, 2)}\n`);
    }
  } catch {
    // manifest not written yet on a first run
  }
}

console.log(`packages: ${VIZ_COPIES.length + 1} files vendored into umbral-viz, `
  + `tokens.js + umbral.css generated for umbral-plot (v${VERSION})`);
