// ── 1. rebuild the demo dataset from raw (UMB-DAT-003) ────────────────────
async function buildData() {
  const raw = await fs.readFile(`${SITE}/data/raw/cabildo-actas.csv`, 'utf8');
  const lines = raw.split('\n').slice(1).filter(Boolean);
  const perYear = new Map();
  const sessions = new Map();
  for (const line of lines) {
    // fields: id_sesion,fecha,no_acta,periodo,punto_n,...
    const [id, fecha] = line.split(',');
    if (!fecha || !/^\d{4}-\d{2}-\d{2}$/.test(fecha)) continue;
    const year = fecha.slice(0, 4);
    perYear.set(year, (perYear.get(year) ?? 0) + 1);
    if (!sessions.has(year)) sessions.set(year, new Set());
    sessions.get(year).add(id);
  }
  const years = [...perYear.keys()].sort();
  const rows = years.map((y) => `${y},${sessions.get(y).size},${perYear.get(y)}`);
  await fs.writeFile(`${SITE}/data/sesiones-por-anio.csv`,
    `anio,sesiones,puntos\n${rows.join('\n')}\n`);
  return { years, rows: rows.length, points: lines.length };
}

// ── 2. copy the guide in, as .qmd ─────────────────────────────────────────
async function copyGuide() {
  await fs.rm(`${SITE}/guide`, { recursive: true, force: true });
  await fs.mkdir(`${SITE}/guide/14-superficies`, { recursive: true });
  await fs.rm(`${SITE}/_includes`, { recursive: true, force: true });
  await fs.mkdir(`${SITE}/_includes/rules`, { recursive: true });

  let n = 0;
  for (const [from, to, base] of [['guide', `${SITE}/guide`, '/guide'],
    ['guide/14-superficies', `${SITE}/guide/14-superficies`, '/guide/14-superficies']]) {
    for (const f of await fs.readdir(from)) {
      if (!f.endsWith('.md') || f === 'README.md') continue;
      const src = await fs.readFile(path.join(from, f), 'utf8');
      const body = src
        // Quarto resolves includes relative to the project root
        .replace(/\{\{<\s*include\s+_includes\//g, '{{< include /_includes/')
        // internal cross-links point at .md in the repo, .qmd on the site
        .replace(/\]\((?!https?:|\/)([\w./-]+)\.md(#[\w-]*)?\)/g,
          (_m, p1, hash) => {
            // resolve relative to the source file's own directory
            const rel = p1.replace(/^\.\//, '');
            return `](${base}/${rel}.qmd${hash ?? ''})`;
          })
        // The guide SHOWS code; it does not run it. An executable fence would make
        // the site try to source() a path that only exists in a downstream repo.
        .replace(/^```\{(\w+)[^}]*\}\s*$/gm, '```\$1');
      // Quarto renders the front-matter title as an <h1>, and the chapter opens with
      // its own '# 04 · Layout'. Both shipped, so every page carried two titles and
      // the TOC nested every section under the second one. Promote the chapter's
      // heading into the front matter and drop it from the body.
      const h1 = /^#\s+(.+)$/m.exec(body);
      const titled = h1
        ? body.replace(/^title:.*$/m, `title: "${h1[1].replace(/"/g, '\\"')}"`)
            .replace(h1[0] + '\n', '')
        : body;
      await fs.writeFile(path.join(to, f.replace(/\.md$/, '.qmd')), titled);
      n += 1;
    }
  }
  for (const f of await fs.readdir('guide/_includes')) {
    if (f === 'README.md') continue;
    const s = await fs.stat(`guide/_includes/${f}`);
    if (s.isDirectory()) continue;
    await fs.copyFile(`guide/_includes/${f}`, `${SITE}/_includes/${f}`);
  }
  for (const f of await fs.readdir('guide/_includes/rules')) {
    if (f === 'README.md') continue;
    await fs.copyFile(`guide/_includes/rules/${f}`, `${SITE}/_includes/rules/${f}`);
  }
  return n;
}

